#!/bin/bash
# Анализирует историю команд и делает выводы

HISTORY_FILE="$HOME/.bash_history"
RECENT_COMMANDS=$(tail -50 "$HISTORY_FILE" 2>/dev/null | uniq)

./scripts/ask-ai.sh "
Ты — локальный AI-помощник проекта Crucix.

Вот последние 50 команд, которые вводил пользователь:
$RECENT_COMMANDS

Проанализируй эти команды и скажи:
1. Какие действия выполнялись в проекте?
2. Что изменилось?
3. Какие есть проблемы или ошибки?
4. Что нужно сделать дальше?

Ответь кратко, на русском языке.
"
