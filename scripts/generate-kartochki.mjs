// Сканируем папку public
const files = fs.readdirSync(publicDir);
const htmlFiles = files.filter(f => f.endsWith('.html') && !f.startsWith('.'));

const modules = htmlFiles.map(filename => {
  const id = filename.replace('.html', '');
  const name = id.charAt(0).toUpperCase() + id.slice(1).replace(/-/g, ' ');
  const category = defaultCategories[id] || 'Прочее';
  const icon = defaultIcons[id] || '📄';
  const description = generateDescription(filename);
  const usage = generateUsage(filename);
  
  return {
    id,
    name,
    url: '/' + id,
    icon,
    category,
    description,
    usage
  };
});

// Сортируем по категориям
modules.sort((a, b) => {
  if (a.category === b.category) return a.name.localeCompare(b.name);
  return a.category.localeCompare(b.category);
});

// Сохраняем в JSON
fs.writeFileSync(outputFile, JSON.stringify({ modules, total: modules.length }, null, 2));
